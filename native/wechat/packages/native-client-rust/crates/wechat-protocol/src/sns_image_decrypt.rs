//! Decode an encrypted SNS image body after its transfer checks succeed.

use zeroize::{Zeroize, ZeroizeOnDrop};

/// Apply the SNS image stream transform to a complete response body.
///
/// The caller must check the response's encryption flag and transfer checksum
/// before calling this function. A numeric SNS key is not an AES key. This
/// transform provides no authentication and does not validate an image format.
pub(crate) fn decrypt_sns_image_in_place(bytes: &mut [u8], key: u64) {
    let mut rng = Isaac64::new(key);
    for chunk in bytes.chunks_mut(8) {
        let mut stream = rng.next().to_be_bytes();
        for (byte, mask) in chunk.iter_mut().zip(stream) {
            *byte ^= mask;
        }
        stream.zeroize();
    }
}

// ISAAC-64, adapted from Bob Jenkins' public-domain reference implementation:
// https://burtleburtle.net/bob/c/isaac64.c
// https://burtleburtle.net/bob/c/isaac64.h
#[derive(Zeroize, ZeroizeOnDrop)]
struct Isaac64 {
    results: [u64; 256],
    memory: [u64; 256],
    remaining: usize,
    a: u64,
    b: u64,
    c: u64,
}

impl Isaac64 {
    fn new(key: u64) -> Self {
        let mut state = Self {
            results: [0; 256],
            memory: [0; 256],
            remaining: 0,
            a: 0,
            b: 0,
            c: 0,
        };
        state.results[0] = key;
        let mut mix = [0x9e37_79b9_7f4a_7c13; 8];
        for _ in 0..4 {
            mix_words(&mut mix);
        }
        for offset in (0..256).step_by(8) {
            for (word, seed) in mix.iter_mut().zip(&state.results[offset..offset + 8]) {
                *word = word.wrapping_add(*seed);
            }
            mix_words(&mut mix);
            state.memory[offset..offset + 8].copy_from_slice(&mix);
        }
        for offset in (0..256).step_by(8) {
            for (word, seed) in mix.iter_mut().zip(&state.memory[offset..offset + 8]) {
                *word = word.wrapping_add(*seed);
            }
            mix_words(&mut mix);
            state.memory[offset..offset + 8].copy_from_slice(&mix);
        }
        mix.zeroize();
        state.generate();
        state.remaining = 256;
        state
    }

    fn generate(&mut self) {
        self.c = self.c.wrapping_add(1);
        self.b = self.b.wrapping_add(self.c);
        for i in 0..256 {
            let x = self.memory[i];
            self.a = match i & 3 {
                0 => !(self.a ^ (self.a << 21)),
                1 => self.a ^ (self.a >> 5),
                2 => self.a ^ (self.a << 12),
                _ => self.a ^ (self.a >> 33),
            };
            self.a = self.a.wrapping_add(self.memory[(i + 128) & 255]);
            let y = self.memory[((x >> 3) & 255) as usize]
                .wrapping_add(self.a)
                .wrapping_add(self.b);
            self.memory[i] = y;
            self.b = self.memory[((y >> 11) & 255) as usize].wrapping_add(x);
            self.results[i] = self.b;
        }
    }

    fn next(&mut self) -> u64 {
        if self.remaining == 0 {
            self.generate();
            self.remaining = 256;
        }
        self.remaining -= 1;
        self.results[self.remaining]
    }
}

fn mix_words(words: &mut [u64; 8]) {
    let [mut a, mut b, mut c, mut d, mut e, mut f, mut g, mut h] = *words;
    a = a.wrapping_sub(e);
    f ^= h >> 9;
    h = h.wrapping_add(a);
    b = b.wrapping_sub(f);
    g ^= a << 9;
    a = a.wrapping_add(b);
    c = c.wrapping_sub(g);
    h ^= b >> 23;
    b = b.wrapping_add(c);
    d = d.wrapping_sub(h);
    a ^= c << 15;
    c = c.wrapping_add(d);
    e = e.wrapping_sub(a);
    b ^= d >> 14;
    d = d.wrapping_add(e);
    f = f.wrapping_sub(b);
    c ^= e << 20;
    e = e.wrapping_add(f);
    g = g.wrapping_sub(c);
    d ^= f >> 17;
    f = f.wrapping_add(g);
    h = h.wrapping_sub(d);
    e ^= g << 14;
    g = g.wrapping_add(h);
    *words = [a, b, c, d, e, f, g, h];
}

#[cfg(test)]
mod tests {
    use super::*;

    // These values were generated by compiling the author's independent C
    // implementation, with randrsl[0]=seed and the other 255 words zero.
    // They cover both seed initialization and regeneration after word 255.
    #[test]
    fn matches_reference_words_before_and_after_regeneration() {
        let fixtures = [
            (
                0,
                [
                    0x9d39247e33776d41,
                    0x2af7398005aaa5c7,
                    0x44db015024623547,
                    0x9c15f73e62a76ae2,
                ],
                [
                    0xa865a54edcc0f019,
                    0x93c42566aef98ffb,
                    0x99e7afeabe000731,
                    0x48cbff086ddf285a,
                    0x7f9b6af1ebf78baf,
                    0x58627e1a149bba21,
                    0x2cd16e2abd791e33,
                    0xd363eff5f0977996,
                ],
            ),
            (
                0x0123456789abcdef,
                [
                    0xd10a71f0453cdb4a,
                    0xa29c4e04143a6cd9,
                    0xf78f8bf8b30fb48c,
                    0xd8500bec7a267f56,
                ],
                [
                    0x0b869967aaa2ee78,
                    0x85e7d69687f4ef71,
                    0x52c98abc2b247c82,
                    0xfe0f2c0f3d4fb2f0,
                    0xb5a3fd826e4e030a,
                    0xf42311f71172bd8c,
                    0x28769e162235a136,
                    0x8c58cab106b1a53f,
                ],
            ),
            (
                u64::MAX,
                [
                    0x7c38fd3a2e7cd8ad,
                    0x64081892c82430f3,
                    0xa8eca8122a6f4607,
                    0xf6943b85ac39b6f0,
                ],
                [
                    0xdb556aaa550f7a30,
                    0xa7a144a636e170ba,
                    0x32281a9061a3e43d,
                    0x8a6d76ba7179bfdd,
                    0x5e47a600222f7310,
                    0xd8c88a61a443b22e,
                    0x09766a5a13641dc7,
                    0x6c81857e2b2d2980,
                ],
            ),
        ];
        for (seed, first, boundary) in fixtures {
            let mut rng = Isaac64::new(seed);
            let actual: Vec<u64> = (0..260).map(|_| rng.next()).collect();
            assert_eq!(&actual[..4], &first, "seed {seed:x}");
            assert_eq!(&actual[252..260], &boundary, "seed {seed:x}");
        }
    }

    #[test]
    fn transform_uses_big_endian_stream_and_preserves_partial_word() {
        let mut bytes = [0xff; 11];
        decrypt_sns_image_in_place(&mut bytes, 1);
        assert_eq!(
            bytes,
            [0x1e, 0x61, 0x2a, 0x2d, 0x35, 0x67, 0x50, 0xd2, 0x58, 0x5e, 0x72]
        );
        decrypt_sns_image_in_place(&mut bytes, 1);
        assert_eq!(bytes, [0xff; 11]);
    }

    #[test]
    fn empty_body_is_unchanged() {
        decrypt_sns_image_in_place(&mut [], u64::MAX);
    }
}
